let currentLang = "en";

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Use requestIdleCallback to defer DOM updates until after paint
  if (window.requestIdleCallback) {
    requestIdleCallback(() => {
      updateTranslations(lang);
    });
  } else {
    // Fallback for browsers without requestIdleCallback
    setTimeout(() => {
      updateTranslations(lang);
    }, 100);
  }

  localStorage.setItem("mlue-lang", lang);
  document.dispatchEvent(new CustomEvent("mlue-language-changed", { detail: { lang } }));
}

function updateTranslations(lang) {
  // Update text content or HTML
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      // Use innerHTML for keys that contain HTML (like hero.title)
      if (key === "hero.title") {
        el.innerHTML = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Update placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update active lang button
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

// Initialize language switcher
document.querySelectorAll(".lang-btn").forEach(btn => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

// Restore saved language
const savedLang = localStorage.getItem("mlue-lang");
if (savedLang && translations[savedLang]) {
  setLanguage(savedLang);
}
